def run_clustering_pipeline(
    n_patients: int = config.N_PATIENTS,
    n_appointments: int = config.N_APPOINTMENTS,
    seed: int = config.SEED,
    sample_size: int = config.CLUSTERING_SAMPLE_SIZE,
    save_artifacts: bool = True,
) -> Dict[str, Any]:
    """Execute complete end-to-end unsupervised clustering pipeline."""
    # 1. Load / generate synthetic data
    df = generate_appointments(n_patients=n_patients, n_appointments=n_appointments, seed=seed)
    from mlcore.data_generation import dataset_hash
    data_hash_val = dataset_hash(df)

    # 2. Extract engagement features
    engagement_df = extract_engagement_features(df)

    # 3. Scale and impute
    scaled_data, imputer, scaler = build_preprocessed_features(engagement_df)

    # 4. Range evaluation across k in [2, 6]
    eval_results = evaluate_cluster_range(scaled_data, k_range=range(2, 7), sample_size=sample_size, seed=seed)
    optimal_k = eval_results["optimal_k"]

    # 5. Fit optimal K-Means
    kmeans = KMeans(n_clusters=optimal_k, random_state=seed, n_init=10)
    km_labels = kmeans.fit_predict(scaled_data)

    # 6. Fit Agglomerative Clustering on subsample for comparison
    rng = np.random.RandomState(seed)
    sub_idx = rng.choice(len(scaled_data), size=min(sample_size, len(scaled_data)), replace=False)
    agg = AgglomerativeClustering(n_clusters=optimal_k, metric="euclidean", linkage="ward")
    agg_labels_sub = agg.fit_predict(scaled_data[sub_idx])
    km_labels_sub = km_labels[sub_idx]
    comp_results = compare_clustering_methods(km_labels_sub, agg_labels_sub)

    # 7. PCA 2D Projection
    pca_coords, pca_model, pca_meta = fit_pca_projection(scaled_data, n_components=2, seed=seed)

    # Transform centroids into PCA space
    centroids_pca = pca_model.transform(kmeans.cluster_centers_)

    # 8. Cluster Profiles
    profiles = profile_clusters(engagement_df, km_labels, optimal_k)
    name_map = {p["cluster_id"]: p["name"] for p in profiles}

    # 9. Prepare subsampled 2D points for UI visualization (e.g. 600 points)
    n_vis = min(600, len(scaled_data))
    vis_idx = rng.choice(len(scaled_data), size=n_vis, replace=False)
    vis_points = []
    for idx in vis_idx:
        c_id = int(km_labels[idx])
        vis_points.append({
            "x": round(float(pca_coords[idx, 0]), 3),
            "y": round(float(pca_coords[idx, 1]), 3),
            "cluster": c_id,
            "cluster_name": name_map[c_id],
            "lead_time_days": round(float(engagement_df.iloc[idx]["lead_time_days"]), 1),
            "previous_appointments": int(engagement_df.iloc[idx]["previous_appointments"]),
            "attendance_ratio": round(float(engagement_df.iloc[idx]["attendance_ratio"]), 2),
        })

    # Prepare DataFrame for static figures
    pca_df = pd.DataFrame({
        "PC1": pca_coords[vis_idx, 0],
        "PC2": pca_coords[vis_idx, 1],
        "cluster": km_labels[vis_idx],
        "cluster_name": [name_map[cid] for cid in km_labels[vis_idx]],
    })

    # 10. Assemble full results dictionary
    final_results = {
        "dataset_size": len(df),
        "n_patients": df["patient_ref"].nunique(),
        "data_hash": data_hash_val,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "disclaimer": NON_CLINICAL_DISCLAIMER,
        "features_used": ENGAGEMENT_FEATURE_NAMES,
        "k_evaluations": eval_results["k_evaluations"],
        "optimal_k": optimal_k,
        "selection_rationale": eval_results["selection_rationale"],
        "cluster_profiles": profiles,
        "methods_comparison": comp_results,
        "pca_summary": pca_meta,
        "pca_centroids": [
            {"cluster": i, "x": round(float(pt[0]), 3), "y": round(float(pt[1]), 3)}
            for i, pt in enumerate(centroids_pca)
        ],
        "sample_points": vis_points,
    }

    # 11. Save artifacts if requested
    if save_artifacts:
        artifact_path = config.ARTIFACT_DIR / config.CLUSTERING_FILENAME
        config.ARTIFACT_DIR.mkdir(parents=True, exist_ok=True)
        with open(artifact_path, "w", encoding="utf-8") as f:
            json.dump(final_results, f, indent=2)

        try:
            fig_paths = generate_clustering_figures(
                eval_results,
                pca_df,
                centroids_pca,
                config.CLUSTERING_PLOT_DIR,
            )
            final_results["figure_paths"] = fig_paths
        except Exception as e:
            final_results["figure_paths"] = {"error": str(e)}

        build_clustering_report_markdown(final_results, config.CLUSTERING_REPORT_PATH)

    return final_results


