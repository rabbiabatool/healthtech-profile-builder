def extract_engagement_features(df: pd.DataFrame) -> pd.DataFrame:
    """Extract and validate non-sensitive operational engagement features."""
    for col in schema.FORBIDDEN_COLUMNS:
        if col in df.columns:
            raise ValueError(f"Forbidden column '{col}' detected in unsupervised engagement data.")
    if schema.TARGET_COLUMN in df.columns:
        # Target column is supervised ground truth, do not use in unsupervised clustering
        pass

    engagement_df = pd.DataFrame(index=df.index)
    engagement_df["lead_time_days"] = df["lead_time_days"].astype(float)
    engagement_df["scheduled_hour"] = df["scheduled_hour"].astype(float)
    engagement_df["previous_appointments"] = df["previous_appointments"].astype(float)
    engagement_df["previous_no_shows"] = df["previous_no_shows"].astype(float)
    
    # Derived engagement metric: attendance ratio in [0, 1]
    denom = engagement_df["previous_appointments"] + 1.0
    attended = (engagement_df["previous_appointments"] - engagement_df["previous_no_shows"]).clip(lower=0.0)
    engagement_df["attendance_ratio"] = attended / denom
    
    engagement_df["distance_km"] = df["distance_km"].astype(float)
    engagement_df["reminder_sent"] = df["reminder_sent"].astype(float)

    return engagement_df[ENGAGEMENT_FEATURE_NAMES]


def build_preprocessed_features(
    engagement_df: pd.DataFrame,
) -> Tuple[np.ndarray, SimpleImputer, StandardScaler]:
    """Impute missing continuous features and scale to zero-mean unit-variance."""
    imputer = SimpleImputer(strategy="median")
    scaler = StandardScaler()

    imputed = imputer.fit_transform(engagement_df.to_numpy())
    scaled = scaler.fit_transform(imputed)
    return scaled, imputer, scaler


def evaluate_cluster_range(
    scaled_data: np.ndarray,
    k_range: range = range(2, 7),
    sample_size: int = config.CLUSTERING_SAMPLE_SIZE,
    seed: int = config.SEED,
) -> Dict[str, Any]:
    """Evaluate K-Means and Agglomerative Clustering across k in [2, 6]."""
    n_samples = len(scaled_data)
    rng = np.random.RandomState(seed)
    
    # Stratified/random subsample for hierarchical clustering efficiency
    subsample_idx = rng.choice(n_samples, size=min(sample_size, n_samples), replace=False)
    subsample_data = scaled_data[subsample_idx]

    k_results = []
    for k in k_range:
        # K-Means
        kmeans = KMeans(n_clusters=k, random_state=seed, n_init=10)
        km_labels = kmeans.fit_predict(scaled_data)
        km_silhouette = float(silhouette_score(scaled_data, km_labels, sample_size=min(5000, n_samples), random_state=seed))
        km_db = float(davies_bouldin_score(scaled_data, km_labels))
        inertia = float(kmeans.inertia_)

        # Agglomerative Clustering on subsample
        agg = AgglomerativeClustering(n_clusters=k, metric="euclidean", linkage="ward")
        agg_labels_sub = agg.fit_predict(subsample_data)
        agg_silhouette = float(silhouette_score(subsample_data, agg_labels_sub, random_state=seed))
        agg_db = float(davies_bouldin_score(subsample_data, agg_labels_sub))

        k_results.append({
            "k": k,
            "kmeans_inertia": round(inertia, 2),
            "kmeans_silhouette": round(km_silhouette, 4),
            "kmeans_davies_bouldin": round(km_db, 4),
            "agglomerative_silhouette": round(agg_silhouette, 4),
            "agglomerative_davies_bouldin": round(agg_db, 4),
        })

    # Find optimal k based on peak silhouette score in K-Means
    best_k_entry = max(k_results, key=lambda r: r["kmeans_silhouette"])
    optimal_k = best_k_entry["k"]

    return {
        "k_evaluations": k_results,
        "optimal_k": optimal_k,
        "selection_rationale": (
            f"k={optimal_k} achieves the best trade-off between silhouette score "
            f"({best_k_entry['kmeans_silhouette']:.4f}) and compactness "
            f"(inertia {best_k_entry['kmeans_inertia']:.2f}) without creating fragmented micro-clusters."
        ),
    }


def fit_pca_projection(
    scaled_data: np.ndarray,
    n_components: int = 2,
    seed: int = config.SEED,
) -> Tuple[np.ndarray, PCA, Dict[str, Any]]:
    """Fit PCA to 2 components and compute explained variance and component loadings."""
    pca = PCA(n_components=n_components, random_state=seed)
    pca_coords = pca.fit_transform(scaled_data)

    evr = pca.explained_variance_ratio_.tolist()
    total_evr = float(np.sum(evr))

    loadings = {}
    for i, comp in enumerate(pca.components_):
        loadings[f"PC{i+1}"] = {
            feat: round(float(weight), 4)
            for feat, weight in zip(ENGAGEMENT_FEATURE_NAMES, comp)
        }

    pca_meta = {
        "explained_variance_ratio": [round(float(v), 4) for v in evr],
        "total_explained_variance": round(total_evr, 4),
        "pc_interpretations": {
            "PC1": "Primary variance axis driven by appointment history volume and attendance consistency.",
            "PC2": "Secondary variance axis driven by scheduling lead time days and travel distance.",
        },
        "component_loadings": loadings,
    }

    return pca_coords, pca, pca_meta


def profile_clusters(
    engagement_df: pd.DataFrame,
    cluster_labels: np.ndarray,
    n_clusters: int,
) -> List[Dict[str, Any]]:
    """Describe each cluster in neutral, non-clinical terms with descriptive statistics."""
    df_with_cluster = engagement_df.copy()
    df_with_cluster["cluster"] = cluster_labels

    cluster_profiles = []
    total_samples = len(engagement_df)
    pop_means = engagement_df.mean()
    pop_stds = engagement_df.std().replace(0, 1.0)

    # Dynamic z-score profiling to ensure distinct, accurate, non-clinical operational archetypes
    for c_id in range(n_clusters):
        sub = df_with_cluster[df_with_cluster["cluster"] == c_id]
        count = len(sub)
        pct = round((count / total_samples) * 100, 2)

        means = {col: round(float(sub[col].mean()), 2) for col in ENGAGEMENT_FEATURE_NAMES}
        medians = {col: round(float(sub[col].median()), 2) for col in ENGAGEMENT_FEATURE_NAMES}
        z_scores = {col: (sub[col].mean() - pop_means[col]) / pop_stds[col] for col in ENGAGEMENT_FEATURE_NAMES}

        # Determine dominant traits
        traits = []
        if z_scores["distance_km"] > 0.8:
            traits.append("Regional / Extended Travel")
        if z_scores["lead_time_days"] > 0.6:
            traits.append("Advance Horizon")
        elif z_scores["lead_time_days"] < -0.6:
            traits.append("Short Horizon")
        if means["reminder_sent"] < 0.2:
            traits.append("Unenrolled Digital Channel")
        elif means["reminder_sent"] > 0.8:
            traits.append("Digital Reminded")
        if z_scores["previous_appointments"] > 0.5 and z_scores["attendance_ratio"] > 0.2:
            traits.append("Routine High Frequency")
        elif z_scores["previous_appointments"] > 0.4 and z_scores["previous_no_shows"] > 0.6:
            traits.append("High-Volume Multi-Visit Cohort")
        elif z_scores["previous_appointments"] < -0.4 and (z_scores["attendance_ratio"] < -0.5 or z_scores["previous_no_shows"] > 0.3):
            traits.append("Low-History Early Friction")
        elif z_scores["attendance_ratio"] < -0.6 or z_scores["previous_no_shows"] > 0.6:
            traits.append("Elevated Schedule Friction")
        if z_scores["scheduled_hour"] > 0.5:
            traits.append("Afternoon Preference")
        elif z_scores["scheduled_hour"] < -0.5:
            traits.append("Morning Preference")

        # Synthesize persona name
        if not traits:
            name = f"General Engagement Cohort {c_id + 1}"
            desc = "Balanced engagement distribution across scheduling horizon, attendance consistency, and reminder channels."
            action = "Standard clinic operational workflow: default SMS reminder 48 hours prior."
        elif "Regional / Extended Travel" in traits:
            name = "Regional Extended-Travel Attendees"
            desc = "Appointments booked with significantly longer travel distances to the clinic facility."
            action = "Provide transit directions, travel-time estimates, and parking guidance in reminder messages."
        elif "Advance Horizon" in traits:
            name = "Long-Horizon Advance Planners"
            desc = "Appointments scheduled weeks to months in advance, requiring sustained commitment."
            action = "Multi-touch notification schedule (14-day email check-in, 48-hour SMS confirmation)."
        elif "Unenrolled Digital Channel" in traits:
            name = "Traditional / Offline Communications Group"
            desc = "Patients not currently receiving automated digital SMS/email reminders."
            action = "Offer clinic desk opt-in for automated appointment reminders during next physical check-in."
        elif "Routine High Frequency" in traits:
            name = "Routine Established Clinic Visitors"
            desc = "High past appointment history with established clinic attendance consistency."
            action = "Express check-in workflow; regular continuity of care scheduling."
        elif "High-Volume Multi-Visit Cohort" in traits:
            name = "High-Volume Recurring Clinic Attendees"
            desc = "Patients with extensive historical appointment volume experiencing occasional scheduling conflicts."
            action = "Flexible rescheduling self-service, SMS calendar integration, and priority appointment transfers."
        elif "Low-History Early Friction" in traits:
            name = "Emerging / Low-History Visitors"
            desc = "Patients with few past clinic appointments and early scheduling hurdles."
            action = "Supportive onboarding, clear clinic directions, and confirmation check-in prompts."
        elif "Elevated Schedule Friction" in traits:
            name = "High-Friction Schedule Cohort"
            desc = "Lower historical attendance ratio and elevated missed appointments indicating logistical or scheduling hurdles."
            action = "Flexible rescheduling options, alternative appointment time offers, and proactive reminder calls."
        elif "Short Horizon" in traits:
            name = "Short-Horizon Responsive Visitors"
            desc = "Appointments scheduled with minimal advance lead time, filling near-term clinic capacity."
            action = "Rapid booking confirmation and waitlist backfill prioritization."
        else:
            name = f"Operational Archetype: {' & '.join(traits[:2])}"
            desc = f"Distinct operational subgroup characterized by {', '.join(traits)}."
            action = "Standard operational reminder protocol with attention to timing preferences."

        cluster_profiles.append({
            "cluster_id": c_id,
            "name": name,
            "description": desc,
            "traits": traits,
            "size": count,
            "percentage": pct,
            "feature_means": means,
            "feature_medians": medians,
            "operational_recommendation": action,
        })

    return cluster_profiles


def compare_clustering_methods(
    km_labels: np.ndarray,
    agg_labels: np.ndarray,
) -> Dict[str, Any]:
    """Compare K-Means vs Agglomerative Clustering using Adjusted Rand Index and Contingency."""
    ari = float(adjusted_rand_score(km_labels, agg_labels))
    nmi = float(normalized_mutual_info_score(km_labels, agg_labels))

    # Cross-tabulation contingency table
    contingency = pd.crosstab(
        pd.Series(km_labels, name="K-Means"),
        pd.Series(agg_labels, name="Agglomerative"),
    ).to_dict()

    return {
        "adjusted_rand_index": round(ari, 4),
        "normalized_mutual_info": round(nmi, 4),
        "contingency_matrix": contingency,
        "method_comparison_summary": (
            f"K-Means and Agglomerative Clustering show moderate-to-high agreement (ARI = {ari:.4f}, NMI = {nmi:.4f}). "
            "Differences stem from K-Means optimizing spherical variance around geometric centroids, "
            "whereas Agglomerative (Ward linkage) builds hierarchical merges minimizing intra-cluster variance without centroid rigidity."
        ),
    }


def generate_clustering_figures(
    evaluation_results: Dict[str, Any],
    pca_df: pd.DataFrame,
    centroids_pca: np.ndarray,
    output_dir: Path,
) -> Dict[str, str]:
    """Generate and save publication-quality static PNG figures."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import seaborn as sns

    output_dir.mkdir(parents=True, exist_ok=True)
    fig_paths = {}

    # Figure 1: Elbow and Silhouette Analysis
    fig, ax1 = plt.subplots(figsize=(8, 5))
    k_data = evaluation_results["k_evaluations"]
    ks = [d["k"] for d in k_data]
    inertias = [d["kmeans_inertia"] for d in k_data]
    km_sil = [d["kmeans_silhouette"] for d in k_data]
    agg_sil = [d["agglomerative_silhouette"] for d in k_data]

    color = "#1f77b4"
    ax1.set_xlabel("Number of Clusters (k)", fontsize=11, fontweight="bold")
    ax1.set_ylabel("K-Means Inertia (SSE)", color=color, fontsize=11, fontweight="bold")
    ax1.plot(ks, inertias, marker="o", color=color, linewidth=2, label="K-Means Inertia (Elbow)")
    ax1.tick_params(axis="y", labelcolor=color)
    ax1.grid(True, linestyle="--", alpha=0.5)

    ax2 = ax1.twinx()
    color2 = "#2ca02c"
    color3 = "#ff7f0e"
    ax2.set_ylabel("Silhouette Score", color=color2, fontsize=11, fontweight="bold")
    ax2.plot(ks, km_sil, marker="s", color=color2, linewidth=2, linestyle="-", label="K-Means Silhouette")
    ax2.plot(ks, agg_sil, marker="^", color=color3, linewidth=2, linestyle="--", label="Agglomerative Silhouette")
    ax2.tick_params(axis="y", labelcolor=color2)

    best_k = evaluation_results["optimal_k"]
    ax1.axvline(x=best_k, color="red", linestyle=":", linewidth=1.5, label=f"Selected k={best_k}")

    fig.suptitle("Unsupervised Cluster Quality: Elbow Method & Silhouette Scores", fontsize=13, fontweight="bold")
    fig.tight_layout()
    elbow_path = output_dir / "clustering_elbow_silhouette.png"
    fig.savefig(elbow_path, dpi=180)
    plt.close(fig)
    fig_paths["elbow_silhouette"] = str(elbow_path)

    # Figure 2: PCA 2D Cluster Projection
    fig, ax = plt.subplots(figsize=(9, 6))
    unique_names = list(pca_df["cluster_name"].unique())
    palette = sns.color_palette("tab10", n_colors=len(unique_names))
    sns.scatterplot(
        data=pca_df,
        x="PC1",
        y="PC2",
        hue="cluster_name",
        palette=palette,
        alpha=0.6,
        s=30,
        ax=ax,
    )
    # Plot centroids
    for c_idx, pt in enumerate(centroids_pca):
        ax.scatter(
            pt[0],
            pt[1],
            color="black",
            marker="X",
            s=120,
            edgecolor="white",
            linewidth=1.5,
            zorder=10,
        )

    ax.set_title("2D PCA Projection of Discovered Engagement Archetypes", fontsize=13, fontweight="bold")
    ax.set_xlabel("Principal Component 1 (History & Attendance Volume)", fontsize=11)
    ax.set_ylabel("Principal Component 2 (Lead Time & Logistics)", fontsize=11)
    ax.grid(True, linestyle="--", alpha=0.4)
    ax.legend(title="Cluster Persona", bbox_to_anchor=(1.02, 1), loc="upper left")

    fig.tight_layout()
    pca_path = output_dir / "clustering_pca_2d.png"
    fig.savefig(pca_path, dpi=180)
    plt.close(fig)
    fig_paths["pca_2d"] = str(pca_path)

    return fig_paths


